class OctaveRuleTest(parameterized.TestCase):
    """The retention rule."""

    @parameterized.parameters(*_GOLDEN)
    def test_mask_matrix(self, name):
        want, geom = _GOLDEN[name]
        np.testing.assert_array_equal(_dense(**geom, length=len(want)), want)

    @parameterized.product(name=list(_GOLDEN), q=[10**3, 10**5, 10**7])
    def test_decoding_holds_the_steady_state(self, name, q):
        geom = _GOLDEN[name][1]
        geometry = taper_geometry(w0=geom["w0"], w1=geom["w0"] << geom["k_levels"])
        keys = np.arange(q - geometry.w1 + 1, q + 1)
        live = np.asarray(
            taper_survives(q, keys, geometry=geometry, coset_index=geom["coset_index"])
        )
        self.assertEqual(int(live.sum()), geometry.slots)
        np.testing.assert_array_equal(q - keys[live][::-1], _AGES_WHILE_DECODING[name])

    def test_raising_w1_only_appends_outer_levels(self):
        # Inside the smaller reach the two geometries retain the identical set, which is what makes
        # `w1` safe to raise at inference and `w0` not.
        wider = _dense(w0=2, k_levels=5, coset_index=0, length=20)
        q, k = np.arange(20)[:, None], np.arange(20)[None, :]
        inside = (q - k) < 16
        np.testing.assert_array_equal(wider & inside, _W2K3_C0 & inside)
        self.assertGreater(int(wider.sum()), int(_W2K3_C0.sum()))


class MipmapRuleTest(parameterized.TestCase):
    """The MIPMAP rule: spans EQUAL at `w0`, counts halving, plus one permanent anchor."""

    @parameterized.parameters(*_MIPMAP_GOLDEN)
    def test_mask_matrix(self, name):
        want, geom = _MIPMAP_GOLDEN[name]
        got = _dense(**geom, length=len(want), rule=TaperRule.MIPMAP)
        np.testing.assert_array_equal(got, want)

    @parameterized.parameters(*_MIPMAP_GOLDEN)
    def test_occupancy_is_flat_at_two_w0_minus_one(self, name):
        """The whole reason this rule exists: halve-on-overflow cycled `w0+1 .. 2*w0` and collapsed
        the verbatim run right after each halve. Here both are flat."""
        want, geom = _MIPMAP_GOLDEN[name]
        w0 = geom["w0"]
        geometry = taper_geometry(w0=w0, rule=TaperRule.MIPMAP)
        self.assertEqual(geometry.slots, 2 * w0 - 1)
        tail = want.sum(axis=1)[geometry.w1 + w0 :]
        np.testing.assert_array_equal(tail, np.full_like(tail, geometry.slots))

    @parameterized.product(name=list(_MIPMAP_GOLDEN), q=[10**3, 10**5, 10**7])
    def test_decoding_holds_the_steady_state(self, name, q):
        geom = _MIPMAP_GOLDEN[name][1]
        geometry = taper_geometry(w0=geom["w0"], rule=TaperRule.MIPMAP)
        # Past the reach only the anchor survives, so the window has to include it to see the rest.
        keys = np.arange(q - geometry.w1 + 1, q + 1, dtype=np.int32)
        live = np.asarray(
            taper_survives(q, keys, geometry=geometry, coset_index=geom["coset_index"])
        )
        np.testing.assert_array_equal(q - keys[live][::-1], _MIPMAP_AGES[name])

    def test_the_anchor_never_ages_out(self):
        """`k_0` is the attention sink a window-based cache reintroduces by hand. Under OCTAVE key 0
        dies at `w1`; here its level is permanent, so it is still there at 10^7."""
        geometry = taper_geometry(w0=16, rule=TaperRule.MIPMAP)
        for coset, k0 in ((0, 0), (1, 15)):
            self.assertTrue(taper_survives(10**7, k0, geometry=geometry, coset_index=coset))
            # Its neighbour is not anchored, so it is gone well before that.
            self.assertFalse(taper_survives(10**7, k0 + 2, geometry=geometry, coset_index=coset))

    @parameterized.parameters(6, 10, 2047, 1, 0)
    def test_a_non_power_of_two_w0_is_rejected(self, w0):
        """`levels = log2(w0)` is both the last level's index and the shift that divides by `w0`;
        they coincide only for a power of two, and only then do the rings sum to `2*w0 - 1`."""
        with self.assertRaisesRegex(ValueError, "power-of-two"):
            taper_geometry(w0=w0, rule=TaperRule.MIPMAP)

    def test_w1_caps_the_rings_rather_than_widening_them(self):
        """`w1` buys DOWN here, not up. Rotating level j covers ages `[j*w0, (j+1)*w0)`, so a stream
        that never reaches level j never populates it -- allocating it is pure waste, and it is the
        expensive half of the budget. The memory pool is where this pays: at C16M1 a 128K sequence
        is 8,192 summaries, so `mem_w0 = 4096` needs 2 rings, not 12. Asking for more than the rule
        can reach RAISES, because there is no wider geometry to grant."""
        full = taper_geometry(w0=4096, rule=TaperRule.MIPMAP)
        self.assertEqual((full.levels, full.w1, full.slots), (12, 49152, 8191))
        capped = taper_geometry(w0=4096, w1=16384, rule=TaperRule.MIPMAP)
        self.assertEqual((capped.levels, capped.w1, capped.slots), (4, 16384, 7681))
        self.assertEqual(taper_geometry(w0=4096, max_seq=16384, rule=TaperRule.MIPMAP), capped)
        with self.assertRaisesRegex(ValueError, "reaches at most 49152"):
            taper_geometry(w0=4096, w1=131072, rule=TaperRule.MIPMAP)


class TWAMaskTest(parameterized.TestCase):
    """Plumbing, independent of the rule."""

    def test_mask_broadcast_shape(self):
        fn = twa_mask_fn(w0=2, coset_index=0, w1=16)
        b, n = 2, 20
        q_pos = jnp.arange(n, dtype=jnp.int32)[None, :, None].repeat(b, axis=0)
        k_pos = jnp.arange(n, dtype=jnp.int32)[None, None, :].repeat(b, axis=0)
        out = fn(q_pos, k_pos)
        self.assertEqual(out.dtype, jnp.bool_)
        np.testing.assert_array_equal(np.asarray(out), np.broadcast_to(_W2K3_C0, (b, n, n)))

    def test_build_mask_compatibility(self):
        """A jnp closure would leak a tracer under `ensure_compile_time_eval()`, and a numpy-array
        closure would be rejected by Pallas as a captured constant."""
        for coset in (0, 1):
            fn = twa_mask_fn(w0=1024, coset_index=coset, w1=131072)
            bm = build_mask(fn, q_seq_len=4096, kv_seq_len=4096, block_q=512, block_k=512)
            self.assertIsInstance(bm, np.ndarray)
            self.assertEqual(bm.dtype, np.bool_)
            self.assertEqual(bm.shape, (8, 8))

    def test_mask_compile_time_eval_numpy(self):
        fn = twa_mask_fn(w0=16, coset_index=0, w1=256)
        with jax.ensure_compile_time_eval():
            out = fn(np.int32(20), np.int32(8))
        self.assertIsInstance(out, (bool, np.bool_, np.ndarray))

    def test_mask_fn_rejects_bad_args(self):
        with self.assertRaisesRegex(ValueError, "w0 must be even"):
            twa_mask_fn(w0=0, coset_index=0, w1=64)
        with self.assertRaisesRegex(ValueError, "w0 must be even"):
            twa_mask_fn(w0=7, coset_index=0, w1=64)
        with self.assertRaisesRegex(ValueError, "coset_index"):
            twa_mask_fn(w0=1024, coset_index=2, w1=8192)

    def test_mask_fn_memoized_for_splash_cache(self):
        """SplashAttention keys its MaskInfo cache on `id(mask_fn)`, so identical arguments must
        return the same object or every layer rebuilds MaskInfo."""
        fn = twa_mask_fn(w0=4096, coset_index=0, w1=131072)
        self.assertIs(fn, twa_mask_fn(w0=4096, coset_index=0, w1=131072))
        # A `w1` between two doublings rounds up to the same reach, so it is the same mask.
        self.assertIs(fn, twa_mask_fn(w0=4096, coset_index=0, w1=100000))
        self.assertIsNot(fn, twa_mask_fn(w0=4096, coset_index=0, w1=65536))
        self.assertIsNot(fn, twa_mask_fn(w0=4096, coset_index=1, w1=131072))
        self.assertIsNot(fn, twa_mask_fn(w0=2048, coset_index=0, w1=131072))
        self.assertIsNot(fn, twa_mask_fn(w0=4096, coset_index=0, w1=262144))

    @parameterized.product(rule=[TaperRule.OCTAVE, TaperRule.MIPMAP], coset=[0, 1])
    def test_declared_band_bounds_the_mask(self, rule, coset):
        """Every (q, k) the mask attends lies within the band it declares to the splash kernel.

        The kernel never visits a KV block outside `[q - left_context, q]` and `[0, sink_len)`, so a
        key the mask keeps outside them is dropped with no error. MIPMAP's anchor is such a key: it
        outlives every level, and declaring only a window would lose it for every late query.
        """
        w0, w1 = 16, 64
        fn = twa_mask_fn(w0=w0, coset_index=coset, w1=w1, rule=rule)
        n = 8 * w0 * taper_geometry(w0=w0, w1=w1, rule=rule).levels  # well past the reach
        q = np.arange(n)[:, None]
        k = np.arange(n)[None, :]
        attended = np.asarray(fn(q, k))
        declared = ((q - k) <= fn.left_context) | (k < getattr(fn, "sink_len", 0))
        self.assertFalse(np.any(attended & ~declared))
        # The sink is load-bearing for MIPMAP: some query past the window still reads the anchor.
        beyond = (q - k) > fn.left_context
        self.assertEqual(bool(np.any(attended & beyond)), rule is TaperRule.MIPMAP)


