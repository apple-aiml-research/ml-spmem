def _dense(w0, coset_index, length, *, k_levels=None, rule=TaperRule.OCTAVE):
    w1 = None if k_levels is None else w0 << k_levels
    fn = twa_mask_fn(w0=w0, coset_index=coset_index, w1=w1, rule=rule)
    index = np.arange(length, dtype=np.int32)
    return np.asarray(fn(index[:, None], index[None, :]))


